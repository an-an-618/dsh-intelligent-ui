  // Incremental growth: a second complete control appears on the next tick.
  const grown = partial + ',{"kind":"badge","text":"Second"}]}'
  const incremental = render(React.createElement(helper.components.RenderUiView, {
    block: { phase: 'start', name: 'render_ui', args: partialArgs(grown) },
    t: undefined,
  }))
  assert.equal(findByClass(incremental, 'dsh-iu2-preview').length, 1)
  assert.ok(textOfRendered(incremental).includes('Second'))

  // Title/description only (no complete node) falls back to the Phase 1 skeleton.
  const skeleton = render(React.createElement(helper.components.RenderUiView, {
    block: { phase: 'preparing', name: 'render_ui', args: partialArgs('{"title":"Only title","description":"Later') },
    t: undefined,
  }))
  assert.equal(findByClass(skeleton, 'dsh-iu2-skeleton').length, 1)
  assert.equal(findByClass(skeleton, 'dsh-iu2-preview').length, 0)

  // No source at all keeps the plain placeholder.
  const empty = render(React.createElement(helper.components.RenderUiView, {
    block: { phase: 'preparing', name: 'render_ui' },
    t: undefined,
  }))
  assert.equal(findByClass(empty, 'dsh-iu2-preview').length, 0)
  assert.ok(textOfRendered(empty).includes(helper.MESSAGES.zh['card.preparing']))

