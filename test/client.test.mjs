function createFakeReact() {
  return {
    createElement(type, props, ...children) {
      const merged = Object.assign({}, props === undefined || props === null ? {} : props)
      // Real React nests children in props; error boundaries rely on it.
      if (children.length === 1) merged.children = children[0]
      else if (children.length > 1) merged.children = children
      return { type, props: merged, children }
    },
    Component: class {
      constructor(props) {
        this.props = props
        this.state = {}
      }

      setState(next) {
        this.state = Object.assign({}, this.state, typeof next === 'function' ? next(this.state) : next)
      }
    },
    Fragment: Symbol('Fragment'),
    memo(component) {
      return component
    },
    useId() {
      return ':r0:'
    },
    useState(initial) {
      return [typeof initial === 'function' ? initial() : initial, () => {}]
    },
    useMemo(factory) {
      return factory()
    },
    useCallback(callback) {
      return callback
    },
    useRef(initial) {
      return { current: initial }
    },
  }
}

function loadClient() {
  let definition
  const window = {
    __ModuleLoader__: {
      load(candidate) {
        definition = candidate
      },
    },
  }
  const context = vm.createContext({ window, console })
  new vm.Script(CLIENT_SOURCE, { filename: CLIENT_PATH }).runInContext(context)
  assert.ok(definition, 'client.js must call window.__ModuleLoader__.load')
  const React = createFakeReact()
  const module = definition.factory((name) => {
    if (name === 'react') return React
    throw new Error('unexpected require(' + JSON.stringify(name) + ')')
  })
  return { definition, module, React }
}

