/* ------------------------------------------------------------------ *
 * Mini renderer
 *
 * A ~60-line static React renderer: it runs function components, dispatches
 * useState/useMemo/useCallback/useRef in call order, renders class components,
 * and honours `getDerivedStateFromError` the way a real error boundary does.
 * One pass only (enough to prove initial render), no DOM and no external code.
 * ------------------------------------------------------------------ */

function mountRenderer(React) {
  /** Per-component-instance hook cells, so setters can drive a rerender. */
  const stores = new Map()
  let current = null
  let rootElement = null

  function storeFor(key) {
    let store = stores.get(key)
    if (store === undefined) {
      store = { values: [], cursor: 0 }
      stores.set(key, store)
    }
    return store
  }

  React.useState = (initial) => {
    const store = current
    const index = store.cursor
    store.cursor += 1
    if (!(index in store.values)) store.values[index] = typeof initial === 'function' ? initial() : initial
    const setter = (next) => {
      const previous = store.values[index]
      const value = typeof next === 'function' ? next(previous) : next
      if (Object.is(value, previous)) return
      store.values[index] = value
    }
    return [store.values[index], setter]
  }
  React.useMemo = (factory) => {
    current.cursor += 1
    return factory()
  }
  React.useCallback = (callback) => {
    current.cursor += 1
    return callback
  }
  React.useRef = (initial) => {
    const store = current
    const index = store.cursor
    store.cursor += 1
    if (!(index in store.values)) store.values[index] = { current: initial }
    return store.values[index]
  }

  function componentKey(type, props, path) {
    const key = props !== undefined && props !== null && props.key !== undefined ? String(props.key) : ''
    const name = typeof type.displayName === 'string'
      ? type.displayName
      : typeof type.name === 'string' && type.name !== ''
        ? type.name
        : 'anonymous'
    return path + '|' + key + '|' + name
  }

  function renderNode(node, path) {
    if (node === null || node === undefined || typeof node === 'boolean') return null
    if (typeof node === 'string' || typeof node === 'number') return String(node)
    if (Array.isArray(node)) {
      const out = []
      for (let index = 0; index < node.length; index++) {
        const rendered = renderNode(node[index], path + '.' + index)
        if (rendered === null) continue
        if (Array.isArray(rendered)) out.push.apply(out, rendered)
        else out.push(rendered)
      }
      return out
    }
    const type = node.type
    const props = node.props
    if (typeof type === 'function' && type.prototype !== undefined && typeof type.prototype.render === 'function') {
      const instance = new type(props)
      let rendered
      try {
        rendered = renderNode(instance.render(), path + '/class')
      } catch (error) {
        if (typeof type.getDerivedStateFromError !== 'function') throw error
        instance.state = Object.assign({}, instance.state, type.getDerivedStateFromError(error))
        rendered = renderNode(instance.render(), path + '/class')
      }
      return rendered
    }
    if (typeof type === 'function') {
      const store = storeFor(componentKey(type, props, path))
      const saved = current
      const savedCursor = store.cursor
      current = store
      store.cursor = 0
      let output
      try {
        output = type(props)
      } finally {
        current = saved
        store.cursor = savedCursor
      }
      return renderNode(output, path + '/out')
    }
    if (typeof type === 'string') {
      const children = []
      if (Array.isArray(node.children)) {
        for (let index = 0; index < node.children.length; index++) {
          const rendered = renderNode(node.children[index], path + '.' + index)
          if (rendered === null) continue
          if (Array.isArray(rendered)) children.push.apply(children, rendered)
          else children.push(rendered)
        }
      }
      return { type, props, children }
    }
    return null
  }

  function render(element) {
    stores.clear()
    rootElement = element
    return renderNode(element, 'root')
  }
  render.rerender = () => renderNode(rootElement, 'root')
  return render
}

function collectRendered(root) {
  const elements = []
  const text = []
  function visit(node) {
    if (node === null || node === undefined) return
    if (typeof node === 'string') {
      text.push(node)
      return
    }
    if (Array.isArray(node)) {
      for (const child of node) visit(child)
      return
    }
    elements.push(node)
    for (const child of node.children) visit(child)
  }
  visit(root)
  return { elements, text: text.join('') }
}

function classNameOf(element) {
  return element.props === undefined || element.props.className === undefined ? '' : String(element.props.className)
}

function findByClass(root, name) {
  return collectRendered(root).elements.filter((element) => classNameOf(element).split(/\s+/).indexOf(name) !== -1)
}

function textOfRendered(root) {
  return collectRendered(root).text
}

