/** `{ parts: [...] }` RichText literal. */
function rich(text) {
  return { parts: [{ k: 'lit', v: text }] }
}

function lit(text) {
  return { k: 'lit', v: text }
}

function expr(ast) {
  return { k: 'expr', e: ast }
}

function ref(name) {
  return { t: 'ref', name }
}

function value(v) {
  return { t: 'lit', v }
}

function bin(op, a, b) {
  return { t: 'bin', op, a, b }
}

/** Compare a value minted inside the vm realm with a local literal. */
function plain(value) {
  return JSON.parse(JSON.stringify(value))
}

/** RichText wrapping one expression AST. */
function richExpr(ast) {
  return { parts: [expr(ast)] }
}

/** RichText wrapping one literal run. */
function richLiteral(text) {
  return { parts: [lit(text)] }
}

